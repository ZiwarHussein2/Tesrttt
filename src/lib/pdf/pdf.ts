import type { ReportDocData } from "@/lib/reports/types";
export type { ReportDocData, ReportSection } from "@/lib/reports/types";

export function downloadReportPdf(data: ReportDocData) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  let y = header(doc, data.companyName, data.title, `${data.reportType} · ${data.scope} · ${data.period}`);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(120);
  doc.text(`Prepared for: ${data.preparedFor}`, MARGIN, y);
  y += 20;

  for (const section of data.sections) {
    y = sectionTitle(doc, section.heading, y);
    if (section.kpis?.length) {
      autoTable(doc, {
        startY: y,
        margin: { left: MARGIN, right: MARGIN },
        body: section.kpis,
        styles: { fontSize: 9, textColor: [40, 40, 40], lineColor: [235, 235, 235], lineWidth: 0.5 },
        columnStyles: { 0: { fontStyle: "bold", cellWidth: 200 } },
        theme: "grid",
      });
      y = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 14;
    }
    if (section.paragraphs?.length) y = paragraphs(doc, section.paragraphs, y);
    if (section.bullets?.length) y = paragraphs(doc, section.bullets, y, true);
    if (section.table) {
      autoTable(doc, {
        startY: y,
        margin: { left: MARGIN, right: MARGIN },
        head: [section.table.columns],
        body: section.table.rows.map((r) => r.map(String)),
        styles: { fontSize: 8, textColor: [60, 60, 60], lineColor: [230, 230, 230], lineWidth: 0.5 },
        headStyles: { fillColor: [23, 23, 23], textColor: [255, 255, 255], fontStyle: "bold" },
        theme: "grid",
      });
      y = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 18;
    }
  }

  footer(doc, data.companyName, data.confidentiality);
  doc.save(`${data.title.toLowerCase().replace(/[^a-z0-9]+/g, "-")}.pdf`);
}
